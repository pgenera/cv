def lerp(a, b, t):
    return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)


def grid(nw, ne, se, sw, rows, cols):
    lines = []
    for i in range(rows):
        t = i / (rows - 1)
        lines.append([lerp(nw, sw, t), lerp(ne, se, t)])
    for j in range(cols):
        t = j / (cols - 1)
        lines.append([lerp(nw, ne, t), lerp(sw, se, t)])
    return lines

